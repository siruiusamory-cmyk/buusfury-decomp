"""The public surface: what the repository says about itself, and to whom.

The repository is public. It should read as an ordinary open-source authoring
SDK and reverse-engineering project, and it must not advertise or depend on how
the work was organised privately: no hosted-service or model product names, no
workflow vocabulary, no private artifact names, no machine-specific paths and no
embedded credentials.

Two design decisions make this screen worth having.

**The terms are not written here.** A file that lists what it forbids can never
pass a scan of the tree it lives in. The patterns and their controls are stored
as base64 in :mod:`tools.quality._public_surface_tables` and decoded at import
time, so this module, and the tests beside it, carry none of the strings they
look for. Print either table with::

    python -c "import base64, tools.quality._public_surface_tables as t; \\
print(base64.b64decode(t.FORBIDDEN_B64).decode())"

**Every screen is narrow by construction.** Each pattern is written to match what
can only mean the excluded thing, and each block carries a probe pair: a string
it must accept and a near-miss it must reject, so a pattern that quietly stops
working fails its own test rather than passing everything. Ordinary technical
senses of the same words are the reason the patterns are narrow: a debugger
session, a build orchestration step, an emulator's Scripting window control and a
game's opponent behaviour are all part of this project's real vocabulary.

Where a legitimate use does match a screen, it is recorded with a written reason
in ``config/public_surface_exceptions.json`` rather than silently tolerated. The
test asserts that every recorded exception is still load-bearing, so the file
cannot rot into a list of permissions for text that is no longer there.
"""

from __future__ import annotations

import argparse
import base64
import json
import re
import subprocess
import sys
from pathlib import Path

from tools.quality import _public_surface_tables as tables

#: Bumped when the report document's shape changes in a way a reader must notice.
SCHEMA = 1

REPOSITORY_ROOT = Path(__file__).resolve().parents[2]
EXCEPTIONS_PATH = REPOSITORY_ROOT / "config" / "public_surface_exceptions.json"

#: Suffixes whose contents are not text. A compressed image can contain any byte
#: sequence at all, so scanning one produces matches that mean nothing.
BINARY_SUFFIXES = frozenset(
    {".bin", ".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico", ".bmp", ".gba",
     ".agb", ".sav", ".srm", ".ss0", ".ss1", ".state", ".dump", ".zip", ".7z"}
)

#: Directories that hold generated or vendored content rather than sources. The
#: repository ignores all of them, so nothing here is part of the public surface.
SKIP_DIRECTORIES = frozenset(
    {".git", "build", "dist", "node_modules", ".venv", "extern", "__pycache__",
     ".pytest_cache", ".astro", ".hypothesis"}
)

#: Dependency lockfiles are generated by a package manager from a manifest. They
#: are checkable content, but nothing in them is authored, so a package name that
#: happens to contain a screened word is not a statement about this project.
SKIP_FILENAMES = frozenset(
    {"package-lock.json", "uv.lock", "yarn.lock", "pnpm-lock.yaml", "poetry.lock"}
)


def _load(encoded: str) -> list[dict]:
    return json.loads(base64.b64decode(encoded).decode("utf-8"))


#: ``(label, compiled pattern)`` for each screen, in table order. The index of an
#: entry is its identity: exceptions refer to screens by index so that a
#: justification never has to restate the term it is about.
FORBIDDEN: tuple[tuple[str, re.Pattern[str]], ...] = tuple(
    (entry["label"], re.compile(entry["pattern"], entry["flags"]))
    for entry in _load(tables.FORBIDDEN_B64)
)

#: ``(label, positive control, negative control)``, one per screen.
PROBES: tuple[tuple[str, str, str], ...] = tuple(
    (label, positive, negative)
    for label, positive, negative in _load(tables.PROBES_B64)
)

EXCEPTION_SCHEMA_VERSION = 1


class ExceptionTable:
    """Justified exceptions, each naming a screen and a path."""

    def __init__(self, entries: list[dict]) -> None:
        self.entries = entries

    @classmethod
    def load(cls, path: Path | None = None) -> "ExceptionTable":
        target = path or EXCEPTIONS_PATH
        if not target.is_file():
            return cls([])
        document = json.loads(target.read_text(encoding="utf-8"))
        if document.get("schema_version") != EXCEPTION_SCHEMA_VERSION:
            raise ValueError(f"{target} has an unexpected schema_version")
        return cls(list(document.get("exceptions", [])))

    def reason_for(self, index: int, relative: str) -> str | None:
        """The written reason this screen is excepted at ``relative``, if any."""
        for entry in self.entries:
            if entry.get("signal_index") != index:
                continue
            pattern = entry.get("path", "")
            if _path_matches(pattern, relative):
                return entry.get("reason") or ""
        return None


def _path_matches(pattern: str, relative: str) -> bool:
    """A path pattern: an exact repository-relative path or a ``*`` glob."""
    if "*" not in pattern:
        return pattern == relative
    expression = re.escape(pattern).replace(r"\*\*", ".*").replace(r"\*", "[^/]*")
    return re.fullmatch(expression, relative) is not None


def tracked_text_files(root: Path | None = None) -> list[str]:
    """Every tracked file that holds text, repository-relative, sorted."""
    base = root or REPOSITORY_ROOT
    listing = subprocess.run(
        ["git", "ls-files", "-z"],
        cwd=base,
        capture_output=True,
        text=True,
        check=False,
    )
    if listing.returncode != 0:
        raise RuntimeError("not a git checkout, or git is unavailable")
    names = [name for name in listing.stdout.split("\0") if name]
    selected = []
    for name in names:
        parts = Path(name).parts
        if any(part in SKIP_DIRECTORIES for part in parts[:-1]):
            continue
        if Path(name).name in SKIP_FILENAMES:
            continue
        if Path(name).suffix.lower() in BINARY_SUFFIXES:
            continue
        selected.append(name)
    return sorted(selected)


def changed_text_files(revision: str, root: Path | None = None) -> list[str]:
    """Tracked text files that differ from ``revision``, plus new untracked ones."""
    base = root or REPOSITORY_ROOT
    diff = subprocess.run(
        ["git", "diff", "--name-only", "--diff-filter=ACMR", revision],
        cwd=base,
        capture_output=True,
        text=True,
        check=False,
    )
    if diff.returncode != 0:
        raise RuntimeError(f"cannot diff against {revision!r}")
    untracked = subprocess.run(
        ["git", "ls-files", "--others", "--exclude-standard"],
        cwd=base,
        capture_output=True,
        text=True,
        check=False,
    )
    names = set(diff.stdout.splitlines()) | set(untracked.stdout.splitlines())
    known = set(tracked_text_files(base))
    return sorted(
        name
        for name in names
        if name in known
        or (
            Path(name).name not in SKIP_FILENAMES
            and Path(name).suffix.lower() not in BINARY_SUFFIXES
            and not any(part in SKIP_DIRECTORIES for part in Path(name).parts[:-1])
        )
    )


#: Suffixes the built site emits. Scanning the artifact means scanning what a
#: visitor actually receives, including anything a build step generated that no
#: source file contains.
BUILT_SUFFIXES = frozenset({".html", ".js", ".mjs", ".css", ".json", ".xml", ".txt", ".svg"})


def built_files(root: Path) -> list[str]:
    """Every text file in a built site directory, relative to that directory."""
    selected = []
    for path in sorted(root.rglob("*")):
        if not path.is_file():
            continue
        if path.suffix.lower() not in BUILT_SUFFIXES:
            continue
        if any(part in SKIP_DIRECTORIES for part in path.relative_to(root).parts[:-1]):
            continue
        selected.append(path.relative_to(root).as_posix())
    return selected


def scan(root: Path | None = None, relative: str = "", *, exceptions: ExceptionTable | None = None,
         text: str | None = None) -> tuple[list[dict], int]:
    """Findings in one file, and the number of hits a justified exception covered.

    ``text`` allows a caller to scan a synthetic string rather than a file, which
    is how the tests exercise a screen without writing the term it looks for.
    """
    base = root or REPOSITORY_ROOT
    table = exceptions if exceptions is not None else ExceptionTable.load()
    if text is None:
        try:
            text = (base / relative).read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            return [], 0
    findings: list[dict] = []
    suppressed = 0
    for number, line in enumerate(text.splitlines(), 1):
        for index, (label, pattern) in enumerate(FORBIDDEN):
            if not pattern.search(line):
                continue
            reason = table.reason_for(index, relative)
            if reason is not None and reason.strip():
                suppressed += 1
                continue
            findings.append(
                {
                    "path": relative,
                    "line": number,
                    "signal_index": index,
                    "signal": label,
                    "text": line.strip()[:160],
                }
            )
    return findings, suppressed


def scan_tree(root: Path | None = None, files: list[str] | None = None) -> dict:
    """The whole report document: findings, per-signal counts and metrics.

    A file that cannot be decoded is reported rather than skipped. Counting it as
    scanned while returning no findings would make the screen look cleanest
    exactly where it is blind, so an unreadable file is its own failure.
    """
    base = root or REPOSITORY_ROOT
    table = ExceptionTable.load(base / "config" / "public_surface_exceptions.json")
    selected = files if files is not None else tracked_text_files(base)
    findings: list[dict] = []
    unreadable: list[str] = []
    suppressed = 0
    for relative in selected:
        try:
            text = (base / relative).read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            unreadable.append(relative)
            continue
        found, covered = scan(base, relative, exceptions=table, text=text)
        findings.extend(found)
        suppressed += covered
    findings.sort(key=lambda item: (item["path"], item["line"], item["signal_index"]))
    counts: dict[str, int] = {}
    for item in findings:
        counts[item["signal"]] = counts.get(item["signal"], 0) + 1
    return {
        "schema": SCHEMA,
        "files_scanned": len(selected) - len(unreadable),
        "files_selected": len(selected),
        "exceptions": len(table.entries),
        "suppressed": suppressed,
        "findings": findings,
        "signal_counts": dict(sorted(counts.items())),
        "unreadable": sorted(unreadable),
    }


def scan_built(directory: Path) -> dict:
    """The same screens over a built site directory rather than the sources.

    The exceptions file does not apply here: a justified exception records why a
    *source* file may legitimately contain a screened word, and the built output
    is not that file. Every finding in an artifact is therefore a finding.
    """
    if not directory.is_dir():
        raise RuntimeError(f"no built site at {directory}")
    selected = built_files(directory)
    findings: list[dict] = []
    for relative in selected:
        found, _ = scan(directory, relative, exceptions=ExceptionTable([]))
        findings.extend(found)
    findings.sort(key=lambda item: (item["path"], item["line"], item["signal_index"]))
    counts: dict[str, int] = {}
    for item in findings:
        counts[item["signal"]] = counts.get(item["signal"], 0) + 1
    return {
        "schema": SCHEMA,
        "built_from": str(directory),
        "files_scanned": len(selected),
        "files_selected": len(selected),
        "exceptions": 0,
        "suppressed": 0,
        "findings": findings,
        "signal_counts": dict(sorted(counts.items())),
    }


def _render(report: dict, stream) -> None:
    print(
        f"public surface: {report['files_scanned']} tracked text files scanned, "
        f"{len(report['findings'])} finding(s), "
        f"{report['suppressed']} suppressed by a written exception",
        file=stream,
    )
    for item in report["findings"]:
        print(
            f"  {item['path']}:{item['line']}: {item['signal']}: {item['text']}",
            file=stream,
        )
    if report["signal_counts"]:
        print("by signal:", file=stream)
        for label, count in report["signal_counts"].items():
            print(f"  {count:5d}  {label}", file=stream)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="public-surface",
        description="Screen tracked public content for private development residue.",
    )
    parser.add_argument(
        "--all",
        action="store_true",
        help="scan every tracked text file (the default)",
    )
    parser.add_argument(
        "--changed",
        metavar="REV",
        nargs="?",
        const="HEAD",
        help="scan only files changed against REV (default HEAD)",
    )
    parser.add_argument(
        "--built",
        metavar="DIR",
        help="scan a built site directory instead of the tracked sources",
    )
    parser.add_argument("--json", metavar="PATH", help="write the report document as JSON")
    parser.add_argument(
        "--no-fail",
        action="store_true",
        help="report findings but always exit 0",
    )
    arguments = parser.parse_args(argv)

    try:
        if arguments.built:
            report = scan_built(Path(arguments.built))
            report["revision"] = None
        elif arguments.changed:
            files = changed_text_files(arguments.changed)
            report = scan_tree(files=files)
            report["revision"] = arguments.changed
        else:
            report = scan_tree()
            report["revision"] = None
    except (RuntimeError, ValueError, json.JSONDecodeError) as error:
        print(f"BLOCKED: {error}", file=sys.stderr)
        return 2

    if arguments.json:
        Path(arguments.json).write_text(
            json.dumps(report, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
            newline="\n",
        )
    _render(report, sys.stdout)

    if report.get("unreadable"):
        print(
            "\nSome tracked files could not be decoded, so they were not "
            "screened. Fix the encoding or remove them from the text tree.",
            file=sys.stderr,
        )
        return 1
    if report["findings"] and not arguments.no_fail:
        print(
            "\nPublic content carries private development residue. Remove it, or "
            "record a written reason in config/public_surface_exceptions.json.",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
