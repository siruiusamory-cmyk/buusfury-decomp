def test_a_data_stated_boundary_splits_the_symbol_without_claiming_an_extent():
    image = bytes(range(0x20))
    cited = {0x08: ["a"]}
    rows = rawlabeled.symbols(image, 0x00, 0x20, cited, extra=(0x14,))
    assert [(row["base"], row["size"]) for row in rows] == [(0x00, 0x08), (0x08, 0x0C),
                                                            (0x14, 0x0C)]
    assert rawlabeled.assert_symbols(rows, 0x00, 0x20, cited, extra=(0x14,)) == 0x20
    text = rawlabeled.emit(image, 0x00, 0x20, (0x14,))
    assert "; no citation: a data-stated boundary (--boundaries)" in text
    assert "|unk_08000014|" in text
    assert blocks_of(text) == [(0x00, 0x14), (0x14, 0x20)]
    assert [token for _, _, token in rawlabeled.blocks(text)] == [
        rawlabeled.slice_name(0x00, 0x14), rawlabeled.slice_name(0x14, 0x20)]


