def test_verify_blocks_names_the_first_byte_a_perturbation_moved():
    rom = bytes((index * 17) & 0xFF for index in range(0x40))
    text = ("|unk_08000010|\n\tINCBIN\tbaserom.gba_0x10_0x20.extracted\n"
            "|unk_08000020|\n\tINCBIN\tbaserom.gba_0x20_0x28.extracted\n")
    root = materialised(rom, text, tempfile.mkdtemp())
    rows = rawlabeled.blocks(text)
    assert rawlabeled.verify_blocks(rom, rows, "the gaps", root) == 0x18
    perturbed = bytearray(rom)
    perturbed[0x23] ^= 1
    message = refusal(lambda: rawlabeled.verify_blocks(bytes(perturbed), rows, "the gaps", root))
    assert message is not None and "byte 0x8000023 differs" in message, message


def test_emit_structured_keeps_a_generated_run_between_the_gaps_it_sits_between():
    image = bytes(0x300)
    plan = rawlabeled.families.Plan(extents={}, members=(), kept={}, clipped={},
                                    runs=((0x100, 0x120), (0x140, 0x160)), gaps=((0x120, 0x140),),
                                    whole_fragments={}, non_whole_fragments={}, union_components=2)
    text = rawlabeled.emit_structured(image, plan, {0x130: ["cited by the test"]}, sites=1, entries=2)
    token_lines = [line for line in text.split("\n") if line.strip().startswith("INCBIN")]
    assert [line.split(None, 1)[1].split("\\")[-1] for line in token_lines] == \
        [rawlabeled.gen_name(0x100, 0x120).split("\\")[-1],
         rawlabeled.slice_name(0x120, 0x130), rawlabeled.slice_name(0x130, 0x140),
         rawlabeled.gen_name(0x140, 0x160).split("\\")[-1]]
    rows = rawlabeled.blocks(text)
    assert [address for address, _, _ in rows] == [0x120, 0x130]
    assert [end - address for address, end, _ in rows] == [0x10, 0x10]
    assert sum(end - start for start, end, _ in rows) == 0x20
