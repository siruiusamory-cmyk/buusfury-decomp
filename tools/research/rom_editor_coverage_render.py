def drift_note(doc: dict) -> str:
    d = doc["baseline"].get("drift")
    if not d:
        return ""
    return ("### Baseline drift measured while this ticket was open\n\n"
            "This census measures `{}`, the pinned baseline, and its row set was frozen and reviewed there. "
            "While the ticket was open, `origin/master` advanced to `{}` (the baseline is an ancestor). The merges "
            "since the baseline are {}. The capability registry is unchanged between the two commits. The product "
            "change is {}.\n\n"
            "Two rows are affected: {}. {}\n\n"
            "{}\n").format(doc["baseline"]["commit"], d["origin_master_while_this_ticket_was_open"],
                           "; ".join("`{}`".format(m) for m in d["merges_since_the_baseline"]),
                           d["product_change"],
                           ", ".join("`{}`".format(r) for r in d["rows_affected"]),
                           d["effect"], d["why_not_rebased"])


