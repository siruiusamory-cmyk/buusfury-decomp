"""The one authority for what this product is and which build produced it.

Two facts live here and nowhere else:

* **the product version** - DragonByte Z's own version string and its numeric
  four-field form. The desktop application, packaging, the About surface, the
  version resource a Windows build embeds, and CI all read this module; none of
  them keeps a copy. A second literal is how a release ends up named one version
  and reporting another, and the remedy in this repository is a test that parses
  the other copy and compares, rather than a promise to keep them in step. This
  is deliberately not the distribution version in ``pyproject.toml``: that names
  the toolkit distribution, which is a different thing from the product a user
  installs, and the randomizers are separate products with their own identity
  constants.

* **the build identity** - the commit, whether the tree had uncommitted changes,
  and when the package was built. A checkout answers that from git. A *packaged*
  build cannot: it has no repository and no git, and asking the filesystem would
  either fail slowly or, far worse, find some unrelated repository through the
  process's working directory and name a commit that did not produce the build.
  So the package build bakes the answer into a generated module
  (``tools/webfoot/_build_identity.py``, ignored by git and written by
  ``python -m tools.webfoot.release_identity --write-record`` before the frozen
  build runs) and a packaged build reports what was baked in. This is the N-26
  closure: the randomizer manifest recorded a null commit in a packaged build.

The pre-release identity is deliberate. ``PRODUCT_VERSION`` is not v1.0 and must
not become it by accident: the version and build identity being visible is one of
the v1.0 gates, and a release candidate is cut by a decision, not by a constant
drifting upward.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from datetime import datetime, timezone
import json
from pathlib import Path
import subprocess
import sys

#: The product a user installs and sees on screen.
PRODUCT_NAME = "DragonByte Z"

#: The pre-release product version. One literal; every surface reads it.
PRODUCT_VERSION = "0.9.0.dev0"

#: The same version as the four integers a Windows version resource is required
#: to carry, where a pre-release suffix has no place. A test asserts the two agree.
VERSION_TUPLE = (0, 9, 0, 0)

#: Where a package build writes the generated record, and where a packaged build
#: reads it. Untracked: it names one machine's commit, not the project's content.
BUILD_RECORD_NAME = "_build_identity.py"

_RECORD_HEADER = (
    "# Generated by `python -m tools.webfoot.release_identity --write-record`.\n"
    "# Not tracked: it records the commit this build was cut from.\n"
)

#: The identity of the application binary that is reading this module. Its
#: ``source`` field says where the answer came from, so a reader never has to
#: guess whether a null commit means "no repository" or "nothing was recorded".
_BUILD_CACHE: "BuildIdentity | None" = None


@dataclass(frozen=True, slots=True)
class ReleaseIdentity:
    """What the product is, independent of any particular build of it."""

    product_name: str
    version: str
    version_tuple: tuple[int, int, int, int]

    @property
    def display(self) -> str:
        """The one-line identity a window title or an About box shows."""
        return f"{self.product_name} {self.version}"

    def to_json(self) -> dict:
        return {
            "name": self.product_name,
            "version": self.version,
            "version_tuple": list(self.version_tuple),
        }


@dataclass(frozen=True, slots=True)
class BuildIdentity:
    """Which build of the product this is, as far as it can be established.

    Any field may be ``None`` when the question cannot be answered. That is a gap
    in the record, never a refusal: provenance is reported honestly, and nothing
    in the product is allowed to fail because a commit could not be named.
    """

    commit: str | None
    dirty: bool | None
    built_at: str | None
    #: ``"record"``, ``"checkout"`` or ``"unknown"``.
    source: str

    def to_json(self) -> dict:
        return {
            "commit": self.commit,
            "dirty": self.dirty,
            "built_at": self.built_at,
            "source": self.source,
        }

    @property
    def display(self) -> str:
        """A short diagnostic line, for a bug report or a log."""
        if self.commit is None:
            return "build unknown"
        suffix = " (modified tree)" if self.dirty else ""
        return f"build {self.commit[:12]}{suffix}"


def release_identity() -> ReleaseIdentity:
    """The product identity. There is no second source."""
    return ReleaseIdentity(PRODUCT_NAME, PRODUCT_VERSION, VERSION_TUPLE)


def is_frozen() -> bool:
    """Whether this process is a packaged application rather than a checkout."""
    return bool(getattr(sys, "frozen", False))


def build_record_path() -> Path:
    """Where the generated build record lives inside this package."""
    return Path(__file__).resolve().with_name(BUILD_RECORD_NAME)


def _recorded() -> BuildIdentity | None:
    """The baked-in identity, or None when there is nothing usable to read.

    A record that cannot be read is treated as absent rather than fatal. The
    record is written by this same module in the same build, so a malformed one
    means the package was tampered with - and refusing to start the application
    over a provenance line would be a worse outcome than reporting it as unknown.
    """
    try:
        from . import _build_identity as record
    except ImportError:
        return None
    commit = getattr(record, "COMMIT", None)
    dirty = getattr(record, "DIRTY", None)
    built_at = getattr(record, "BUILT_AT", None)
    if commit is not None and not isinstance(commit, str):
        return None
    if dirty is not None and not isinstance(dirty, bool):
        return None
    if built_at is not None and not isinstance(built_at, str):
        return None
    return BuildIdentity(commit, dirty, built_at, "record")


def _git(*arguments: str) -> str | None:
    """Run one read-only git command against this checkout, or report nothing.

    The working directory is derived from this file, never taken from the process:
    a caller that happens to be standing in some other repository must not have
    that repository's revision recorded as this build's provenance. Started
    without a console window, because a windowed build that flashed a console on
    every run would be a worse defect than the provenance it was fetching.
    """
    creation_flags = 0
    if sys.platform == "win32":
        creation_flags = getattr(subprocess, "CREATE_NO_WINDOW", 0x08000000)
    try:
        result = subprocess.run(
            ["git", *arguments],
            cwd=Path(__file__).resolve().parents[2],
            capture_output=True,
            text=True,
            timeout=10,
            creationflags=creation_flags,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    if result.returncode != 0:
        return None
    return result.stdout.strip()


def _checkout() -> BuildIdentity:
    """What the checkout this is running from says about itself."""
    commit = _git("rev-parse", "HEAD")
    if not commit:
        return BuildIdentity(None, None, None, "unknown")
    status = _git("status", "--porcelain")
    return BuildIdentity(
        commit, None if status is None else bool(status), None, "checkout"
    )


def build_identity() -> BuildIdentity:
    """The identity of this build, read once and cached.

    A checkout is asked first and the baked record second, so a developer who has
    a record lying around from an earlier package build still gets the live answer
    about the tree they are actually running. A packaged build has no checkout to
    ask and reports the record, which is the only thing that can be true there.
    """
    global _BUILD_CACHE
    if _BUILD_CACHE is None:
        if is_frozen():
            _BUILD_CACHE = _recorded() or BuildIdentity(None, None, None, "unknown")
        else:
            live = _checkout()
            _BUILD_CACHE = live if live.commit is not None else (
                _recorded() or live
            )
    return _BUILD_CACHE


def write_build_record(path: str | Path | None = None) -> Path:
    """Bake this checkout's identity into the generated record.

    Called by a packaging script before the frozen build runs, so the packaged
    application can name the commit it was cut from. It writes a module rather
    than a data file on purpose: a module travels inside a frozen build through
    the ordinary import graph, while a data file has to be declared in the
    packaging spec and silently disappears from the package when it is not.
    """
    destination = Path(path) if path is not None else build_record_path()
    live = _checkout()
    built_at = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    destination.write_text(
        _RECORD_HEADER
        + f"COMMIT = {live.commit!r}\n"
        + f"DIRTY = {live.dirty!r}\n"
        + f"BUILT_AT = {built_at!r}\n",
        encoding="utf-8",
        newline="\n",
    )
    return destination


def identity_document() -> dict:
    """Both identities as one JSON-serialisable document, for CI and packaging."""
    return {
        "schema_version": 1,
        "product": release_identity().to_json(),
        "build": build_identity().to_json(),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="release-identity",
        description=(
            "Report DragonByte Z's product version and the identity of the build "
            "reading it, or bake that identity into a packaged build."
        ),
    )
    parser.add_argument(
        "--json", action="store_true", help="print the identity document as JSON"
    )
    parser.add_argument(
        "--write-record",
        action="store_true",
        help="write the generated build record a packaged build reads",
    )
    arguments = parser.parse_args(argv)

    if arguments.write_record:
        print(write_build_record())
        return 0
    if arguments.json:
        print(json.dumps(identity_document(), indent=2, sort_keys=True))
        return 0
    print(release_identity().display)
    print(build_identity().display)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
