def test_the_committed_files_name_their_own_slices_and_still_split_at_every_citation():
    rom = require_rom()
    assembly = open(os.path.join(ROOT, "asm", "rest_of_the_game.s")).read()
    sources = {name: open(os.path.join(ROOT, "asm", name), errors="replace").read()
               for name in sorted(os.listdir(os.path.join(ROOT, "asm"))) if name.endswith(".s")}
    slices = gate.incbin_ranges()
    runs = committed_runs()
    plain = [key for key, (_, whole) in runs.items() if whole]
    assert len(plain) >= 53, "expected 2 + 7 + 41 + 2 + 2 wholly INCBINed fragments, found %d" % len(plain)
    assert len(plain) < len(runs), "no interleaved fragment (labeled gaps between INCBINed runs)"
    for start, (end, whole) in runs.items():
        name = "rawlabeled_%x.s" % start
        text = open(os.path.join(ROOT, "asm", name)).read()
        rows = rawlabeled.blocks(text)
        if whole:
            assert rawlabeled.verify(rom, start, end, text) == end - start, name
            assert rows[0][0] == start and rows[-1][1] == end, name
            if rawlabeled.EXPLICIT_CHANNEL in text:
                assert "; cited by " in text, name
                named = {base for base in cited_bases(text) if start < base < end}
                assert {address for address, _, _ in rows} <= {start} | named, name
            else:
                cited = rawlabeled.citations(rom, start, end)
                extra = rawlabeled.boundaries(boundary_file(start))
                assert cited or extra, \
                    "%s: neither a cited base inside the run nor a data-stated boundary (P-457)" % name
                expected = sorted({start} | set(cited) | {base for base in extra
                                                          if start <= base < end})
                assert [address for address, _, _ in rows] == expected, name
            for address, _, _ in rows:
                assert text.count("|unk_%08X|" % (BASE + address)) == 2, hex(address)
        else:
            rawlabeled.verify_blocks(rom, rows, name)
        assert not [token for _, _, token in rows
                    if (token_span := rawlabeled.token_span(token)) and not (start <= token_span[0]
                                                                            < token_span[1] <= end)], name
        assert [file for file, body in sources.items() if "INCLUDE %s" % name in body], name
        assert not [file for file, body in sources.items()
                    if file != name and rawlabeled.slice_name(start, end) in body], name
        if whole or rows:
            broken = bytearray(rom)
            broken[(start + (end - start) // 2) if whole else rows[0][0]] ^= 0x01
            assert refusal(lambda: (rawlabeled.verify(bytes(broken), start, end, text) if whole
                                    else rawlabeled.verify_blocks(bytes(broken), rows, name))) \
                is not None


