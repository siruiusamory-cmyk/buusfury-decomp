def test_a_gap_an_overlap_an_uncited_base_and_a_short_body_are_each_refused():
    cases = (
        ({0x08: ["a"], 0x14: ["b"]}, [rows_of(0x00, 8), rows_of(0x14, 4)],
         "ends at 0x8, the next starts at 0x14"),
        ({0x08: ["a"]}, [rows_of(0x00, 12), rows_of(0x08, 8)],
         "ends at 0xc, the next starts at 0x8"),
        ({0x08: ["a"]}, [rows_of(0x00, 8), rows_of(0x0A, 8)],
         "not the run start and is not a cited base"),
        ({0x08: ["a"]}, [rows_of(0x00, 8), {"base": 0x08, "size": 0x10, "data": bytes(4),
                                            "citations": ["a"]}],
         "carries 4 bytes, its extent says 16"),
    )
    for cited, rows, message in cases:
        try:
            rawlabeled.assert_symbols(rows, 0x00, 0x18, cited)
        except ValueError as error:
            assert message in str(error), (message, str(error))
        else:
            raise AssertionError("no refusal for %s" % message)


