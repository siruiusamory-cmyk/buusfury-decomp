DOC_R19 = os.path.join(RESEARCH, "R19_NULL_CENSUS.md")
ROM = os.path.join(ROOT, "baserom.gba")
FENCE = (0x179A50, 0x2B8BC8)
R19_HEAD = "## The rows the table above does not carry"
STREAM_HEAD = "## The opcode streams the `+0x30` field names"
R19_AFTER = "## Why they stay raw"
PAIR = re.compile(r"([0-9A-Fa-f]{8})=([0-9A-Fa-f]{8})")
HEX = re.compile(r"0x[0-9A-Fa-f]+")
RUNTIME = re.compile(r"cited by runtime read")
ROM_BASE = 0x08000000
IWRAM = (0x03000000, 0x03008000)
EWRAM = (0x02000000, 0x02040000)


def read_rom():
    with open(ROM, "rb") as handle:
        return handle.read()


def census(region):
    out = []
    with open(CENSUS, newline="") as handle:
        for row in csv.DictReader(handle):
            if row["region"] != region:
                continue
            out.append({"start": int(row["start"], 16), "end": int(row["end"], 16),
                        "bytes": int(row["bytes"]), "class": row["class"], "region": row["region"]})
    return out


def inside_fence(row):
    return FENCE[0] <= row["start"] and row["end"] <= FENCE[1]


def citations(comments, span):
    text = " ".join(line for _number, line in comments.get(span, []))
    if not RUNTIME.search(text):
        return None
    return [(int(pc, 16), int(address, 16)) for pc, address in PAIR.findall(text)]


def address_words(rom, start, length):
    count = 0
    for at in range((-start) % 4, length - 3, 4):
        value = struct.unpack_from("<I", rom, start + at)[0]
        if ROM_BASE <= value < ROM_BASE + len(rom) or IWRAM[0] <= value < IWRAM[1] \
                or EWRAM[0] <= value < EWRAM[1]:
            count += 1
    return count


def shape_stats(rom, start, length):
    body = rom[start:start + length]
    shares = collections.Counter(body)
    entropy = -sum((count / length) * math.log2(count / length) for count in shares.values())
    return entropy, shares[0] / length, address_words(rom, start, length)


def r02_text(rows, comments):
    cited = [row for row in rows if citations(comments, (row["start"], row["end"]))]
    pairs = sum(len(citations(comments, (row["start"], row["end"]))) for row in cited)
    lines = []
    add = lines.append
