"""The project file: the input image's digest and the edit list, replayed on export.

The format is TOML through the SDK's own serializer, so the same edits always
produce the same bytes. Two things that serializer cannot carry are handled here:

- it emits tables, never arrays of tables, so each edit is one table under
  ``[edits.000]``, ``[edits.001]``, ... in the order the edits were made;
- it refuses control characters, and a dialogue record legitimately carries
  control units, so every free-text value is escaped: a character below 0x20,
  0x7f, or a literal ``%`` becomes ``%XX``. Every escaped character is below
  0x100, so the pair is exact and the round trip is lossless.

The file holds no generated bytes: an export replays this list from the base
image. No Qt is imported, so a test drives save and load with no window open.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

from tools.webfoot import textedit
from tools.webfoot.project.format import ProjectFormatError, dump_toml, load_toml

#: What a saved project is called, so the open and save dialogs agree.
SUFFIX = ".bftproject"

#: The only layout this build writes. A file that says anything else is refused
#: rather than guessed at.
FORMAT = 1


class ProjectFileError(ValueError):
    """The project file cannot be read as one."""


@dataclass(frozen=True, slots=True)
class Project:
    """Where an edit list came from, and the edits themselves."""

    rom_sha256: str
    rom_name: str
    canonical_sha256: str | None
    edits: tuple[object, ...]

    def edit_counts(self) -> dict[str, int]:
        counts: dict[str, int] = {"slot": 0, "record": 0}
        for edit in self.edits:
            counts[_kind_of(edit)] += 1
        return counts


def _kind_of(edit: object) -> str:
    if isinstance(edit, textedit.SlotEdit):
        return "slot"
    if isinstance(edit, textedit.RecordEdit):
        return "record"
    raise ProjectFileError(
        f"{edit!r} is not a SlotEdit or a RecordEdit. A per-occurrence rename is stored "
        "as the record decisions it produced, not as the batch rule.")


def pack(value: str) -> str:
    """Escape the characters the TOML writer cannot carry, reversibly."""
    return "".join(f"%{ord(character):02X}"
                   if ord(character) < 0x20 or ord(character) == 0x7F or character == "%"
                   else character for character in value)


def unpack(value: str) -> str:
    """Reverse :func:`pack`, refusing rather than inventing an escape."""
    out: list[str] = []
    position = 0
    while position < len(value):
        if value[position] == "%":
            pair = value[position + 1:position + 3]
            if len(pair) != 2:
                raise ProjectFileError(f"{value!r} ends inside a % escape")
            try:
                out.append(chr(int(pair, 16)))
            except ValueError as error:
                raise ProjectFileError(f"%{pair} is not a %XX escape") from error
            position += 3
            continue
        out.append(value[position])
        position += 1
    return "".join(out)


def _table(edit: object) -> dict[str, Any]:
    if isinstance(edit, textedit.SlotEdit):
        return {"kind": "slot", "slot": edit.slot, "old": pack(edit.old), "new": pack(edit.new)}
    if isinstance(edit, textedit.RecordEdit):
        return {"kind": "record", "selector": edit.selector, "start": edit.start,
                "length": edit.length, "old": pack(edit.old), "new": pack(edit.new)}
    raise ProjectFileError(
        f"{edit!r} is not a SlotEdit or a RecordEdit. A per-occurrence rename is stored "
        "as the record decisions it produced, not as the batch rule.")


def _edit(entry: Any) -> object:
    if not isinstance(entry, dict):
        raise ProjectFileError("an [edits.NNN] entry is not a table")
    kind = entry.get("kind")
    for field in ("old", "new"):
        if not isinstance(entry.get(field), str):
            raise ProjectFileError(f"a {kind!r} edit has no {field!r} string")
    if kind == "slot":
        slot = entry.get("slot")
        if not isinstance(slot, int) or isinstance(slot, bool):
            raise ProjectFileError("a 'slot' edit has no 'slot' integer")
        return textedit.SlotEdit(slot=slot, old=unpack(entry["old"]), new=unpack(entry["new"]))
    if kind == "record":
        numbers = {}
        for field in ("selector", "start", "length"):
            value = entry.get(field)
            if not isinstance(value, int) or isinstance(value, bool):
                raise ProjectFileError(f"a 'record' edit has no {field!r} integer")
            numbers[field] = value
        return textedit.RecordEdit(numbers["selector"], numbers["start"], numbers["length"],
                                   unpack(entry["old"]), unpack(entry["new"]))
    raise ProjectFileError(
        f"{kind!r} is not a 'slot' or a 'record' edit. A per-occurrence rename is stored as "
        "the record decisions it produced, not as the batch rule.")


def encode(project: Project) -> str:
    """The project as TOML text. Same edits, same bytes, always."""
    header: dict[str, Any] = {
        "format": FORMAT,
        "rom_sha256": project.rom_sha256,
        "rom_name": pack(project.rom_name),
    }
    if project.canonical_sha256:
        header["canonical_sha256"] = project.canonical_sha256
    edits = {f"{index:03d}": _table(edit) for index, edit in enumerate(project.edits)}
    return dump_toml({"project": header, "edits": edits})


def decode(text: str) -> Project:
    """Read a project, naming the first thing that is wrong with it."""
    try:
        document = load_toml(text)
    except ProjectFormatError as error:
        raise ProjectFileError(str(error)) from error
    header = document.get("project")
    if not isinstance(header, dict):
        raise ProjectFileError("the file has no [project] table")
    if header.get("format") != FORMAT:
        raise ProjectFileError(
            f"the file is project format {header.get('format')!r}; this build reads {FORMAT}")
    digest = header.get("rom_sha256")
    if not isinstance(digest, str) or len(digest) != 64:
        raise ProjectFileError("the project does not record the input image's SHA-256")
    entries = document.get("edits", {})
    if not isinstance(entries, dict):
        raise ProjectFileError("[edits] is not a table")
    canonical = header.get("canonical_sha256")
    name = header.get("rom_name")
    return Project(
        rom_sha256=digest,
        rom_name=unpack(name) if isinstance(name, str) else "",
        canonical_sha256=canonical if isinstance(canonical, str) else None,
        edits=tuple(_edit(entries[key]) for key in sorted(entries)),
    )


def save(project: Project, path: str | Path) -> None:
    Path(path).write_text(encode(project), encoding="utf-8", newline="\n")


def load(path: str | Path) -> Project:
    target = Path(path)
    try:
        return decode(target.read_text(encoding="utf-8"))
    except OSError as error:
        raise ProjectFileError(f"{target.name} cannot be read: {error}") from error


def of(model: textedit.Model, edits: tuple[object, ...]) -> Project:
    """The project a session would save: the model's own identity, and its edits."""
    return Project(rom_sha256=model.sha256, rom_name=Path(model.path).name,
                   canonical_sha256=model.retail_sha256, edits=edits)
