def require_rom():
    path = os.path.join(ROOT, "baserom.gba")
    if not os.path.exists(path):
        pytest.skip("%s is absent, so this ROM-gated test cannot run" % path)
    return open(path, "rb").read()

BASE = 0x08000000
HEADER = re.compile(r"the (census run|structured block's retail gaps) "
                    r"0x([0-9a-fA-F]+)\.\.0x([0-9a-fA-F]+) as "
                    r"(?:LABELED RAW DATA|GENERATED RECORD DATA)")
CITED_ADDRESS = re.compile(r"0x([0-9A-Fa-f]{8})")
RECOMP_READ = re.compile(r"read 0x([0-9A-Fa-f]{8})")
RUNTIME_READ = re.compile(r"=\s*([0-9A-Fa-f]{8})")


def cited_bases(text):
    out = set()
    for line in text.split("\n"):
        body = line.lstrip()
        if not body.startswith(";") or "cited by" not in body:
            continue
        if RECOMP_READ.search(body):
            tokens = RECOMP_READ.findall(body)
        elif "runtime read" in body:
            tokens = RUNTIME_READ.findall(body)
        else:
            tokens = CITED_ADDRESS.findall(body)
        out |= {int(token, 16) - BASE for token in tokens}
    return out


def refusal(call):
    try:
        call()
    except ValueError as error:
        return str(error)
    return None


def blocks_of(text):
    return [(start, end) for start, end, _ in rawlabeled.blocks(text)]


def committed_runs():
    runs = {}
    directory = os.path.join(ROOT, "asm")
    for name in sorted(os.listdir(directory)):
        if not (name.startswith("rawlabeled_") and name.endswith(".s")):
            continue
        text = open(os.path.join(directory, name), errors="replace").read()
        match = HEADER.search(text)
        assert match, name
        start, end = int(match.group(2), 16) - BASE, int(match.group(3), 16) - BASE
        runs[start] = (end, rawlabeled.tiled(rawlabeled.blocks(text), start, end))
    return runs


def boundary_file(start):
    path = os.path.join(HERE, "rawlabeled_%x_bounds.txt" % start)
    return path if os.path.exists(path) else None


def rows_of(base, size, cited=False):
    return {"base": base, "size": size, "data": bytes(size), "citations": ["0x08000000"] if cited
            else []}


def materialised(image, text, root):
    for start, end, token in rawlabeled.blocks(text):
        with open(os.path.join(root, token), "wb") as handle:
            handle.write(image[start:end])
    return root


