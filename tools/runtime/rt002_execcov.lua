-- RUNTIME-EXEC-001: execution-coverage probe for the Buu's Fury census rows
-- classified `code-without-entry` (565 rows / 43,909 B, RAW_REMAINDER.csv).
--
-- WHY TWO TARGET CHANNELS. mGBA 0.11 has no execute WATCHPOINT. At the exact
-- build this probe targets (0.11.0.0, mGBA-build-2026-08-27-win64-9128-
-- c65e8a3d4666b0ea68a01578232452f31b185332) the exposed API is:
--   setBreakpoint(callback, address[, segment])          execute, ONE address
--   setWatchpoint(callback, address, type[, segment])     one address
--   setRangeWatchpoint(callback, min, max, type[, segment])
--   clearBreakpoint(cbid)
-- and the watchpoint type is an int from enum mWatchpointType
-- (include/mgba/debugger/debugger.h at the build's source commit):
--   WATCHPOINT_WRITE = 1, WATCHPOINT_READ = 2, WATCHPOINT_RW = 3,
--   WATCHPOINT_CHANGE = 4, WATCHPOINT_WRITE_CHANGE = 5.
-- There is no execute member, so execution is observable only through
-- setBreakpoint, one address at a time. Covering all 43,909 bytes that way is
-- ~21,955 hardware breakpoints and is not attempted.
--
-- CHANNELS, kept separate so a silence is attributable (mgba-runtime.md s.8):
--   EXEC    one execute breakpoint per row START (bounded by RT002_BP_LIMIT),
--           so "the row's first instruction executed" is a measurement.
--   READ    one READ range watchpoint per whole row, so any touch of any byte
--           of a row is seen. Whether an instruction FETCH is visible to a READ
--           watchpoint is measured by the CONTROL channel, not assumed.
--   CONTROL a READ range watchpoint over a code address that a previous
--           owner-driven session (docs/research/RUNTIME_CITED_ROWS.md,
--           rt001-owner-1) recorded as a pc: 0x0800F0B4. Firing means a READ
--           watchpoint over ROM code sees instruction fetch, so a READ row hit
--           is execution evidence; silence with a live frame tick means the
--           READ channel is a data-read channel only. Set RT002_CONTROL=0 to
--           disable it.
--   LIVENESS frame ticks into <run>/frame-tick.txt, per-channel counters into
--           rt002-liveness.txt, and a verbose first-hit envelope into
--           rt002-info.txt (raw pc register, the address the callback carried,
--           cpsr, width, accessType) so the `thumb` column can be audited.
--
-- Read-only with respect to the emulated machine: this file arms breakpoints and
-- watchpoints and writes host files inside the run directory. It writes no
-- emulated memory and presses no key at all, so the observer guarantee in
-- docs/skills/mgba-runtime.md section 7 holds.
--
-- COLUMNS. rt002-hits.csv is `pc,frame,row_start,thumb,channel`. The contract's
-- four columns are all present; `channel` is added because an EXEC hit and a
-- READ hit are otherwise indistinguishable, and without it a hit could not be
-- read as execution at all. `thumb` is the cpsr T bit at the hit (1/0), or -1
-- when cpsr is not readable - "not established" is written, never guessed.
-- Rows are deduplicated by (pc, row_start, channel): a pc that touches several
-- rows yields one row per row, which is what makes row attribution complete.
-- A pc of 0 falls back to the callback's own address and is counted in the
-- liveness file as pc_fallback, so a dead pc register is visible rather than
-- silently collapsing the log.
--
-- Inputs (environment, so one file serves every probe):
--   RT002_OUT       directory for these outputs (default: the run directory)
--   RT002_LIST      file of "<start hex> <end hex> <bytes>" rows, BUS addresses
--                   (RT002_LIST is generated by build_rt002_list.py, which adds
--                   0x08000000 to the census file offsets)
--   RT002_CSV       CSV path (default <RT002_OUT>rt002-hits.csv)
--   RT002_CAP       stop after this many distinct rows (default 20000)
--   RT002_BP_LIMIT  maximum execute breakpoints to arm (default 100000, i.e.
--                   all); the armed set is written to rt002-exec-armed.txt
--   RT002_CONTROL   "<start hex> <end hex>" for the READ control range, or 0
--   RT002_ARM       "0" arms nothing and only proves the identity channels
--
-- LIMITS. The EXEC channel observes row starts only; a row whose interior is
-- entered directly is invisible to it. The READ channel observes touches, not
-- fetches, unless the CONTROL channel proves otherwise in the same run. A run
-- whose frame-tick.txt stops advancing is a stalled instrument, never a
-- negative (pitfall P-097 for a breakpoint-heavy observer on this build).

local marker_path = rom011_marker_path
assert(marker_path and #marker_path > 0, "marker path not provided")
local exp_dir = marker_path:gsub("[^/\\]+$", "")

local out_dir    = os.getenv("RT002_OUT") or exp_dir
local csv_path   = os.getenv("RT002_CSV") or (out_dir .. "rt002-hits.csv")
local list_path  = os.getenv("RT002_LIST") or (out_dir .. "rt002-rows.txt")
local api_path   = out_dir .. "rt002-api.txt"
local live_path  = out_dir .. "rt002-liveness.txt"
local info_path  = out_dir .. "rt002-info.txt"
local armed_path = out_dir .. "rt002-exec-armed.txt"
local tick_path  = exp_dir .. "frame-tick.txt"
local cap        = tonumber(os.getenv("RT002_CAP") or "") or 20000
local bp_limit   = tonumber(os.getenv("RT002_BP_LIMIT") or "") or 100000
local control    = os.getenv("RT002_CONTROL") or "0800F0B4 0800F0B6"

local function w(path, text, mode)
    local f = io.open(path, mode or "w")
    if f then f:write(text) f:close() end
end

local cpsr_ok, cpsr_probe = pcall(function() return emu:readRegister("cpsr") end)

local log = {
    "emu=" .. tostring(emu ~= nil),
    "setBreakpoint=" .. tostring(emu and emu.setBreakpoint ~= nil),
    "clearBreakpoint=" .. tostring(emu and emu.clearBreakpoint ~= nil),
    "setWatchpoint=" .. tostring(emu and emu.setWatchpoint ~= nil),
    "setRangeWatchpoint=" .. tostring(emu and emu.setRangeWatchpoint ~= nil),
    "readRegister=" .. tostring(emu and emu.readRegister ~= nil),
    "readRegister_cpsr=" .. tostring(cpsr_ok and cpsr_probe or "ERR"),
    "romSize=" .. tostring(emu and emu:romSize()),
    "gameCode=" .. tostring(emu and emu:getGameCode()),
    "marker=" .. marker_path,
    "list=" .. list_path,
    "cap=" .. tostring(cap),
    "bp_limit=" .. tostring(bp_limit),
    "control=" .. control,
}
w(api_path, table.concat(log, "\n") .. "\n")

local arm_enabled = (os.getenv("RT002_ARM") or "1") ~= "0"
if arm_enabled then
    assert(emu and emu.setRangeWatchpoint and emu.setBreakpoint and emu.clearBreakpoint,
        "this mGBA build has no Lua execute-breakpoint API; refusing to run a channel that cannot see execution")
end

local rows = {}
for line in io.lines(list_path) do
    local a, b, n = line:match("^%s*(%x+)%s+(%x+)%s*(%d*)")
    if a and b then
        rows[#rows + 1] = { start = tonumber(a, 16), stop = tonumber(b, 16), bytes = tonumber(n or "0") or 0 }
    end
end
assert(#rows > 0, "no rows in " .. list_path)

local control_range = nil
do
    local a, b = control:match("^%s*(%x+)%s+(%x+)")
    if a and b then control_range = { start = tonumber(a, 16), stop = tonumber(b, 16) } end
end

local csv = assert(io.open(csv_path, "w"))
csv:write("pc,frame,row_start,thumb,channel\n")
csv:flush()

local hits, frames, capped = 0, 0, false
local exec_hits, read_hits, control_hits, pc_fallback = 0, 0, 0, 0
local exec_armed, read_armed = 0, 0
local dirty = false
local seen, ids = {}, {}

local function disarm()
    for _, id in ipairs(ids) do
        if id then pcall(function() emu:clearBreakpoint(id) end) end
    end
end

local function cpu_pc(fallback)
    local ok, value = pcall(function() return emu:readRegister("pc") end)
    local pc = ok and tonumber(value) or nil
    if not pc or pc == 0 then
        pc_fallback = pc_fallback + 1
        return fallback or 0
    end
    if pc < 0 then pc = pc % 4294967296 end
    return pc
end

local function cpu_thumb()
    local ok, value = pcall(function() return emu:readRegister("cpsr") end)
    local cpsr = ok and tonumber(value) or nil
    if not cpsr then return -1 end
    if math.floor(cpsr % 64 / 32) == 1 then return 1 end
    return 0
end

local function row_of(address)
    for _, r in ipairs(rows) do
        if address >= r.start and address < r.stop then return r.start end
    end
    return 0
end

local function record(pc, row_start, channel)
    local key = string.format("%08X:%08X:%s", pc, row_start, channel)
    if seen[key] then return end
    seen[key] = true
    hits = hits + 1
    csv:write(string.format("%08X,%d,%08X,%d,%s\n", pc, frames, row_start, cpu_thumb(), channel))
    dirty = true
    if hits % 20 == 0 then csv:flush() end
    if hits >= cap and not capped then
        capped = true
        disarm()
        csv:flush()
        w(live_path, string.format("CAP-REACHED frames=%d hits=%d exec=%d read=%d control=%d\n",
            frames, hits, exec_hits, read_hits, control_hits))
    end
end

local function reg(name)
    local ok, value = pcall(function() return emu:readRegister(name) end)
    return ok and tostring(value) or "ERR"
end

local function first_hit(kind, info, address)
    local keys = {}
    for k, v in pairs(info or {}) do keys[#keys + 1] = tostring(k) .. "=" .. tostring(v) end
    table.sort(keys)
    w(info_path, string.format(
        "%s frame=%d address=%08X raw_pc=%s cpsr=%s\ninfo=%s\n",
        kind, frames, address, reg("pc"), reg("cpsr"), table.concat(keys, ",")))
end

local function on_exec(info)
    local address = tonumber(info and info.address) or 0
    if exec_hits == 0 then first_hit("exec", info, address) end
    exec_hits = exec_hits + 1
    record(cpu_pc(address), row_of(address), "exec")
end

local function on_read(info)
    local address = tonumber(info and info.address) or 0
    local row = row_of(address)
    if row == 0 then
        if control_hits == 0 then first_hit("control", info, address) end
        control_hits = control_hits + 1
        return
    end
    if read_hits == 0 then first_hit("read", info, address) end
    read_hits = read_hits + 1
    record(cpu_pc(address), row, "read")
end

if arm_enabled then
    for _, r in ipairs(rows) do
        local ok, id = pcall(function() return emu:setRangeWatchpoint(on_read, r.start, r.stop, 2, -1) end)
        if ok and id and id >= 0 then
            read_armed = read_armed + 1
        else
            w(api_path, string.format("read arm FAILED 0x%08X..0x%08X -> %s\n", r.start, r.stop, tostring(id)), "a")
        end
    end

    local lines = {}
    for _, r in ipairs(rows) do
        if exec_armed >= bp_limit then break end
        local ok, id = pcall(function() return emu:setBreakpoint(on_exec, r.start, -1) end)
        if ok and id and id >= 0 then
            ids[#ids + 1] = id
            exec_armed = exec_armed + 1
            lines[#lines + 1] = string.format("%08X %08X", r.start, r.bytes)
        else
            w(api_path, string.format("exec arm FAILED 0x%08X -> %s\n", r.start, tostring(id)), "a")
        end
    end
    w(armed_path, table.concat(lines, "\n") .. (exec_armed > 0 and "\n" or ""))

    if control_range then
        local ok, id = pcall(function()
            return emu:setRangeWatchpoint(on_read, control_range.start, control_range.stop, 2, -1)
        end)
        if ok and id and id >= 0 then
            ids[#ids + 1] = id
        else
            w(api_path, string.format("control arm FAILED 0x%08X..0x%08X -> %s\n",
                control_range.start, control_range.stop, tostring(id)), "a")
        end
    end
end

w(live_path, string.format("READY rows=%d exec_armed=%d read_armed=%d cap=%d bp_limit=%d control=%s\n",
    #rows, exec_armed, read_armed, cap, bp_limit, tostring(control_range ~= nil)))

callbacks:add("frame", function()
    frames = frames + 1
    if dirty then csv:flush() dirty = false end
    if frames % 10 == 0 then w(tick_path, tostring(frames)) end
    if frames % 300 == 0 then
        w(live_path, string.format(
            "frames=%d hits=%d exec=%d read=%d control=%d exec_armed=%d read_armed=%d pc_fallback=%d\n",
            frames, hits, exec_hits, read_hits, control_hits, exec_armed, read_armed, pc_fallback))
    end
    if frames == 600 or frames == 3600 then
        pcall(function() emu:screenshot(out_dir .. "rt002-shot-" .. tostring(frames) .. ".png") end)
    end
end)
