def load() -> dict:
    with io.open(JSON_PATH, encoding="utf-8") as fh:
        return json.load(fh)


def rows_of(doc: dict, area: str) -> list[dict]:
    return [r for r in doc["rows"] if r["area"] == area]


def sentence(text: str) -> str:
    t = text.strip()
    return t if t.endswith(".") else t + "."


#: The census row whose prose states the editable-map figure.
MAP_FIGURE_ROW = "map-layout-chunk-grids"

#: That row states the figure as ``N of M maps expose an editable layer``.
_MAP_FIGURE = re.compile(r"(\d+) of (\d+) maps expose an editable layer")


def map_figure(doc: dict) -> tuple[int, int]:
    """The editable and total map counts, read from the row that owns them.

    The summary repeats this figure in prose. Reading it from the row is what lets
    the render check see a row change: a literal here would keep both the renderer
    and the generated documents on the old number, and the documents would still
    match the renderer, which is the drift this module's docstring says cannot
    happen. Fails closed rather than rendering a sentence with no figure.
    """
    row = next((r for r in doc["rows"] if r["id"] == MAP_FIGURE_ROW), None)
    if row is None:
        raise ValueError("no census row {} to read the map figure from".format(MAP_FIGURE_ROW))
    match = _MAP_FIGURE.search(row["edit"])
    if match is None:
        raise ValueError(
            "row {} no longer states the editable map figure as "
            "'N of M maps expose an editable layer'".format(MAP_FIGURE_ROW)
        )
    return int(match.group(1)), int(match.group(2))


def matrix_row(r: dict) -> str:
    g = r["games"]
    cells = []
    for game in ("buus_fury", "logii", "log1"):
        c = g[game]
        marker = "" if c["basis"] == "MEASURED" else " (ni)"
        cells.append(STATE_SHORT[c["state"]] + marker)
    ek = g["buus_fury"]["engine_knowledge"]
    rt = g["buus_fury"]["runtime_evidence"]
    tool = re.split(r"(?<=\.)\s+", r["external_tool"].split(";")[0], maxsplit=1)[0]
    return "| `{}` | {} | {} | {} | {} | {} | {} | {} |".format(
        r["id"], r["name"], cells[0], cells[1], cells[2], ek, rt, tool)


def row_block(r: dict) -> str:
    g = r["games"]
    lines = ["#### `{}`".format(r["id"]), ""]
    lines.append("**{}** - {}".format(r["name"], r["description"]))
    lines.append("")
    for label, key in (
        ("Semantic read", "read"),
        ("Existing-record edit", "edit"),
        ("New-record authoring", "author"),
        ("Cross-reference and navigation", "xref"),
        ("Raw backing range", "raw_range"),
        ("Validation and rebuild", "validation_rebuild"),
        ("Current product and UI exposure", "ui"),
        ("Known restrictions", "restrictions"),
        ("External tool currently required", "external_tool"),
    ):
        lines.append("- **{}:** {}".format(label, r[key]))
    lines.append("- **Per-game state:** " + "; ".join(
        "{} = {} (basis {}, engine knowledge {}, runtime {}, confidence {})".format(
            GAME_TITLES[game], g[game]["state"], g[game]["basis"],
            g[game]["engine_knowledge"], g[game]["runtime_evidence"], g[game]["confidence"])
        for game in ("buus_fury", "logii", "log1")))
    lines.append("- **Evidence authority:** {}".format(r["evidence_authority"]))
    lines.append("- **Open research questions:** " + " ".join(r["open_questions"]))
    lines.append("- **Evidence references:** " + "; ".join(r["evidence_refs"]))
    lines.append("")
    return "\n".join(lines)


