def test_a_record_run_is_spliced_between_the_labelled_rows_it_cuts():
    text = ("; PATH-100-999 / R-RAW-001: the census run 0x08000000..0x08000020 as LABELED RAW DATA.\n"
            "\n\tEXPORT\t|unk_08000000|\n|unk_08000000|\n; cited by 0x08000100\n\n"
            "\tINCBIN\tbaserom.gba_0x0_0x20.extracted\n")
    run = "build\\mapcontainer\\map_00000008_00000010.bin"
    new, inserted, retired = rawlabeled.spliced(text, [(0x08, 0x10, run)])
    assert (inserted, retired) == (1, [])
    assert [line.split()[-1] for line in new.split("\n") if "INCBIN" in line] == [
        "baserom.gba_0x0_0x8.extracted", run, "baserom.gba_0x10_0x20.extracted"]
    assert "|unk_08000010|" in new and new.count("|unk_08000000|") == 2
    two = ("\tEXPORT\t|unk_08000000|\n|unk_08000000|\n\n\tINCBIN\tbaserom.gba_0x0_0x8.extracted\n"
            "\tEXPORT\t|unk_08000008|\n|unk_08000008|\n; cited by 0x08000200\n\n"
            "\tINCBIN\tbaserom.gba_0x8_0x20.extracted\n")
    new, inserted, retired = rawlabeled.spliced(two, [(0x00, 0x10, run)])
    assert (inserted, retired) == (1, [0x08])
    assert [line.split()[-1] for line in new.split("\n") if "INCBIN" in line] == [
        run, "baserom.gba_0x10_0x20.extracted"]
    assert "|unk_08000008|" not in new


