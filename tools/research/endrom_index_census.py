from __future__ import annotations

import argparse
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
RUNS = os.path.join(ROOT, "docs", "research", "RUNTIME_READ_RUNS.csv")
ROW_HITS = os.path.join(ROOT, "docs", "research", "RUNTIME_READ_ROW_HITS.csv")
DOC_OUT = os.path.join(ROOT, "docs", "research", "ENDROM_INDEX_CENSUS.md")
SCENE = "endrom-warp"
LIVENESS_PC = 0x08008A0E
ARRAYS = (
    {"start": 0x762270, "end": 0x76ACC0, "stride": 36, "index": "0x0801B2F4",
     "reader": "0x0801B2B4"},
    {"start": 0x72D6B8, "end": 0x7315A8, "stride": 60, "index": "0x08024714",
     "reader": "0x080246B4"},
    {"start": 0x77B2A8, "end": 0x77C41C, "stride": 12, "index": "0x0803C31C",
     "reader": "0x0803C2F8"},
)


def number(text, base=10):
    if text is None or text in ("", "None"):
        return None
    return int(text, base)


def read_runs(path=None):
    out = []
    with open(RUNS if path is None else path, newline="") as handle:
        for row in csv.DictReader(handle):
            if row.get("scene") != SCENE:
                continue
            out.append({"run": number(row["run"]), "scene": row["scene"],
                        "status": row["status"], "arrival": number(row["arrival"]),
                        "witness": number(row["witness"]) or 0,
                        "witness_pc": number(row["witness_pc"], 16),
                        "log_sha256": row["log_sha256"], "log_lines": number(row["log_lines"]) or 0})
    return sorted(out, key=lambda row: row["run"])


def read_row_hits(path=None):
    out = []
    with open(ROW_HITS if path is None else path, newline="") as handle:
        for row in csv.DictReader(handle):
            out.append({"run": number(row["run"]), "start": number(row["start"], 16),
                        "hits": number(row["hits"]) or 0,
                        "pcs": [pc for pc in (row.get("pcs") or "").split(";") if pc],
                        "max_address": number(row.get("max_address"), 16)})
    return out


def census(runs, row_hits):
    out = []
    counted = {run["run"] for run in runs}
    for array in ARRAYS:
        mine = [row for row in row_hits if row["run"] in counted
                and row["start"] == array["start"] and row["hits"]]
        highest = max((row["max_address"] for row in mine
                       if row["max_address"] is not None), default=None)
        size = array["end"] - array["start"]
        out.append({**array, "bytes": size, "whole": size // array["stride"],
                    "tail": size % array["stride"],
                    "runs": sorted({row["run"] for row in mine}),
                    "hits": sum(row["hits"] for row in mine),
                    "highest": None if highest is None else highest - array["start"],
                    "index_reached": None if highest is None else
                    (highest - array["start"]) // array["stride"],
                    "pcs": sorted({pc for row in mine for pc in row["pcs"]})})
    return out


def live(runs):
    return [run for run in runs if run["witness"] and run["witness_pc"] == LIVENESS_PC]


def verdict(row):
    if row["index_reached"] is None:
        return "raw, not reached"
    return "raw, lower bound"


def doc_text(runs, rows, row_hits):
    alive = live(runs)
    maps = [run["run"] for run in runs]
    lines = []
    add = lines.append
    add("# End-of-ROM index census: how far the read watch reached")
    add("")
    add("Generated by `tools/research/endrom_index_census.py`; `--check` re-derives this page from")
    add("`docs/research/RUNTIME_READ_RUNS.csv` and `docs/research/RUNTIME_READ_ROW_HITS.csv`.")
    add("")
    add("## What was run")
    add("")
    add("* The watch is the read-logging runtime outside this repository, driven headless by")
    add("  `tools/runtime/recomp_read_sweep.py`: one CSV line per ROM read, `pc,lr,addr,width,frame`.")
    add("* The watched ranges are the three rows below in full, plus the liveness range the driver")
    add("  appends (`0x%06x..0x%06x`)." % (0x8E2E0, 0x8E2F0))
    add("* One run per map: the saved game's `map:0038/transition:0000` record is retargeted in a")
    add("  private ROM copy, so the engine's own key resolver and loader load the requested map.")
    confirmed = [run for run in runs if run["status"] == "ok"]
    add("* %d runs over map %d..%d, one per map; %d confirmed the arrival map and %d carry the"
        % (len(runs), min(maps, default=0), max(maps, default=0), len(confirmed), len(alive)))
    add("  liveness read at `pc 0x%08x`, whose count proves the read channel was open in that run."
        % LIVENESS_PC)
    add("  Every run's digest, arrival and liveness count is the `%s` row of"
        % SCENE)
    add("  `docs/research/RUNTIME_READ_RUNS.csv`.")
    add("* The method's ceiling: a session reaches indices, and the highest index it reaches is a")
    add("  lower bound. No run states a count.")
    add("")
    add("## Per row")
    add("")
    add("| row | bytes | stride | whole records | tail | index site | reader body | runs that read it |")
    add("|---|---|---|---|---|---|---|---|")
    for row in rows:
        add("| `0x%06X..0x%06X` | %d | %d | %d | %d | `%s` | `%s` | %d |"
            % (row["start"], row["end"], row["bytes"], row["stride"], row["whole"], row["tail"],
               row["index"], row["reader"], len(row["runs"])))
    add("")
    add("| row | hits | highest offset read | highest index | end marker | verdict |")
    add("|---|---|---|---|---|---|")
    for row in rows:
        add("| `0x%06X` | %d | %s | %s | none: no reader body tests one | %s |"
            % (row["start"], row["hits"],
               "-" if row["highest"] is None else "`+0x%X`" % row["highest"],
               "-" if row["index_reached"] is None else str(row["index_reached"]),
               verdict(row)))
    add("")
    add("A terminator would have to be tested by a reader body. `docs/research/ENDROM_BOUND_CENSUS.md`")
    add("quotes every compare in the three bodies and none of them reads a record as an end marker, so")
    add("a watched read can only state which record the game used, never that a record is the last.")
    add("")
    add("## The runs that read a row")
    add("")
    add("| map | arrival | liveness | row | hits | reader pcs | highest index |")
    add("|---|---|---|---|---|---|---|")
    reached = 0
    for run in runs:
        for row in rows:
            mine = [hit for hit in row_hits if hit["run"] == run["run"]
                    and hit["start"] == row["start"] and hit["hits"]]
            if not mine:
                continue
            reached += 1
            highest = max(hit["max_address"] for hit in mine)
            add("| `map:%04d` | %s | %d | `0x%06X` | %d | %s | %d |"
                % (run["run"], "-" if run["arrival"] is None else run["arrival"], run["witness"],
                   row["start"], sum(hit["hits"] for hit in mine),
                   ";".join(sorted({pc for hit in mine for pc in hit["pcs"]})),
                   (highest - row["start"]) // row["stride"]))
    if not reached:
        add("| - | - | - | - | - | - | - |")
    add("")
    add("## What the census decides")
    add("")
    for row in rows:
        if row["index_reached"] is None:
            add("* `0x%06X..0x%06X`: %d B stay raw-data; no automated run read a byte of the row, so"
                % (row["start"], row["end"], row["bytes"]))
            add("  no index was reached and the census states none.")
        else:
            add("* `0x%06X..0x%06X`: %d B stay raw-data; the watch reached index %d of the %d whole"
                % (row["start"], row["end"], row["bytes"], row["index_reached"], row["whole"]))
            add("  records the row holds and no more, so the array's end is still unstated.")
    add("")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    runs = read_runs()
    row_hits = read_row_hits()
    rows = census(runs, row_hits)
    text = doc_text(runs, rows, row_hits)
    for row in rows:
        print("0x%06X %6d B stride %2d runs %3d hits %6d highest index %s"
              % (row["start"], row["bytes"], row["stride"], len(row["runs"]), row["hits"],
                 "-" if row["index_reached"] is None else row["index_reached"]))
    print("runs %d live %d row reads %d" % (len(runs), len(live(runs)),
                                            sum(len(row["runs"]) for row in rows)))
    if args.check:
        with open(DOC_OUT, encoding="utf-8") as handle:
            if handle.read() != text:
                raise SystemExit("%s is not the census these tables derive"
                                 % os.path.relpath(DOC_OUT, ROOT))
        print("CHECK: the census matches the run and row-hit tables")
        return 0
    with open(DOC_OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print("wrote %s (%d B)" % (os.path.relpath(DOC_OUT, ROOT), len(text)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
