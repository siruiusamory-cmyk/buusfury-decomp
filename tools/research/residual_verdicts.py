    add("`0x179A50..0x2B8BC8`, %d rows / %d B; the map block's own five"
        % (len(rows), sum(row["bytes"] for row in rows)))
    add("`R02` rows are carried by `docs/research/MAP_BLOCK_NULL_CENSUS.md`. The region is")
    add("`incbin_census.REGIONS`'")
    add("`PATH-100-012 runtime-cited rows (a read consumer, no extent)`: every row is named by a read")
    add("the emulator logged, and no instrument states a field, a count or an extent inside it.")
    add("")
    add("Generated by `tools/research/residual_verdicts.py` (`python tools/research/residual_verdicts.py")
    add("--r02`); `--check` re-derives this file.")
    add("")
    add("## What measured the rows, and its denominator")
    add("")
    add("| channel | instrument | denominator | hits |")
    add("|---|---|---|---|")
    add("| a read observed at run time | the carrier comment's `cited by runtime read` line, session "
        "`rt001`, `(pc, first address read)` pairs | %d rows | %d rows / %d pair(s) |"
        % (len(rows), len(cited), pairs))
    add("| a decoded reader in transcribed code | `tools/research/citations_in_source.py` channels P "
        "and A | 2,783 ledger Thumb/ARM rows | %d row(s) |"
        % sum(1 for row in rows if not citations(comments, (row["start"], row["end"]))))
    add("| the 452-map read sweep | `docs/research/REGION_READS.csv` | 452 maps | 0 rows: the sweep "
        "logs no read of a `R02` row |")
    add("")
    add("A runtime read states the instruction and the address it read; it states no field boundary")
    add("and no extent, so a row it names converts only when a layout inside it is measured too.")
