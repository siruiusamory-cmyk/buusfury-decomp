def test_a_missing_or_wrong_slice_fails_the_round_trip():
    image = bytes(range(0x20))
    text = rawlabeled.emit(image, 0x00, 0x20)
    root = materialised(image, text, tempfile.mkdtemp())
    assert rawlabeled.verify(image, 0x00, 0x20, text, root) == 0x20

    token = rawlabeled.blocks(text)[0][2]
    os.remove(os.path.join(root, token))
    assert "is missing" in refusal(lambda: rawlabeled.verify(image, 0x00, 0x20, text, root))
    for start, end, name in rawlabeled.blocks(text):
        with open(os.path.join(root, name), "wb") as handle:
            handle.write(image[start:end])

    for start, end, name in rawlabeled.blocks(text):
        with open(os.path.join(root, name), "wb") as handle:
            handle.write(bytes([image[start] ^ 0x5A]) + image[start + 1:end])
        message = refusal(lambda: rawlabeled.verify(image, 0x00, 0x20, text, root))
        assert message is not None and "differs" in message, (name, message)
        with open(os.path.join(root, name), "wb") as handle:
            handle.write(image[start:end])


